/* Escapes user-controlled strings before they're interpolated into an HTML
   email body, to prevent HTML/markup injection into outbound emails. */
export function escapeHtml(input: string): string {
  return input
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
